package com.tracy.lifehackormyth

import android.content.Intent
import android.os.Bundle
import android.util.Log
import android.widget.Button
import androidx.activity.enableEdgeToEdge
import androidx.appcompat.app.AppCompatActivity
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat

class MainActivity : AppCompatActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        // Draws the app behind the system bars (generated by the Android Studio template)
        enableEdgeToEdge()
        setContentView(R.layout.activity_main)

        // Keeps content clear of the status and navigation bars (template code)
        ViewCompat.setOnApplyWindowInsetsListener(findViewById(R.id.main)) { v, insets ->
            val systemBars = insets.getInsets(WindowInsetsCompat.Type.systemBars())
            v.setPadding(systemBars.left, systemBars.top, systemBars.right, systemBars.bottom)
            insets
        }

        // Find the Start button defined in activity_main.xml
        val startButton = findViewById<Button>(R.id.startButton)
        // When Start is tapped, log it and open the question screen
        startButton.setOnClickListener {
            Log.d("MainActivity", "Start button clicked - launching QuestionActivity")
            // An Intent tells Android which screen to open next
            val intent = Intent(this, QuestionActivity::class.java)
            startActivity(intent)
        }
    }
}
